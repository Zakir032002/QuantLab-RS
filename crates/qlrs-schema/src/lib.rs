/// Interned strings occupy one byte arena; hash collisions use linked dense IDs.
#[derive(Debug, Clone, Default)]
pub struct Interner {
    bytes: Vec<u8>,
    offsets: Vec<u32>,
    lengths: Vec<u32>,
    next: Vec<u32>,
    heads: HashMap<u64, Id, foldhash::fast::RandomState>,
    hasher: foldhash::fast::RandomState,
}
impl PartialEq for Interner {
    fn eq(&self, other: &Self) -> bool {
        self.bytes == other.bytes && self.offsets == other.offsets && self.lengths == other.lengths
    }
}
impl Eq for Interner {}
impl Interner {
    /// Find an existing symbol without inserting or allocating.
    #[must_use]
    pub fn lookup(&self, text: &str) -> Option<Id> {
        let mut cursor = self.heads.get(&self.hasher.hash_one(text)).copied()?;
        while cursor != NONE {
            if self.get(cursor) == Some(text) {
                return Some(cursor);
            }
            cursor = *self.next.get(cursor as usize)?;
        }
        None
    }
    /// Intern without allocating an owned copy of every hash-map key.
    pub fn intern(&mut self, text: &str) -> Result<Id, String> {
        let hash = self.hasher.hash_one(text);
        let mut cursor = self.heads.get(&hash).copied().unwrap_or(NONE);
        while cursor != NONE {
            if self.get(cursor) == Some(text) {
                return Ok(cursor);
            }
            cursor = self.next.get(cursor as usize).copied().unwrap_or(NONE);
        }
        let id = checked_index(self.offsets.len()).map_err(|_| "too many interned identifiers")?;
        let offset = checked_index(self.bytes.len()).map_err(|_| "string arena exceeds 4 GiB")?;
        let length = checked_index(text.len()).map_err(|_| "identifier exceeds 4 GiB")?;
        let end = offset
            .checked_add(length)
            .ok_or("string arena exceeds 4 GiB")?;
        if end == NONE {
            return Err("string arena exhausted".into());
        }
        self.offsets.push(offset);
        self.lengths.push(length);
        self.next.push(self.heads.insert(hash, id).unwrap_or(NONE));
        self.bytes.extend_from_slice(text.as_bytes());
        Ok(id)
    }
    /// Resolve an interned identifier.
    #[must_use]
    pub fn get(&self, id: Id) -> Option<&str> {
        let start = *self.offsets.get(id as usize)? as usize;
        let len = *self.lengths.get(id as usize)? as usize;
        std::str::from_utf8(self.bytes.get(start..start.checked_add(len)?)?).ok()
    }
    /// Number of distinct interned strings.
    #[must_use]
    pub fn len(&self) -> usize {
        self.offsets.len()
    }
    /// Whether the interner has no symbols.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.offsets.is_empty()
    }
    /// Release spare arena and hash capacity after construction.
    pub fn compact(&mut self) {
        self.bytes.shrink_to_fit();
        self.offsets.shrink_to_fit();
        self.lengths.shrink_to_fit();
        self.next.shrink_to_fit();
        self.heads.shrink_to_fit();
    }
    /// Approximate retained allocation, including hash-map capacity.
    #[must_use]
    pub fn heap_bytes(&self) -> usize {
        self.bytes.capacity()
            + (self.offsets.capacity() + self.lengths.capacity() + self.next.capacity()) * 4
            + self.heads.capacity() * 24
    }
}

