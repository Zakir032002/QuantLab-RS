/// Dense interned string identifier.
pub type Id = u32;
/// Sentinel for an unresolved dense reference.
pub const NONE: u32 = u32::MAX;

/// Convert a column/CSR index without using the reserved u32 sentinel.
pub fn checked_index(value: usize) -> Result<u32, &'static str> {
    let value = u32::try_from(value).map_err(|_| "U-LIMIT-INDEX")?;
    if value == NONE {
        Err("U-LIMIT-INDEX")
    } else {
        Ok(value)
    }
}

/// Overall outcome, in decreasing evidence precedence.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum Status {
    #[doc = "Consistent state or tag."]
    Consistent,
    #[doc = "Violation state or tag."]
    Violation,
    #[doc = "Inconclusive state or tag."]
    Inconclusive,
    #[doc = "Unsupported state or tag."]
    Unsupported,
}
impl Status {
    /// CLI exit status for a verification verdict.
    #[must_use]
    pub const fn exit_code(self) -> u8 {
        match self {
            Self::Consistent => 0,
            Self::Violation => 2,
            Self::Inconclusive => 3,
            Self::Unsupported => 4,
        }
    }
}

/// Declared rounding of cash observations.
