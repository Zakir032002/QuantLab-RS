/// Compact representation used by replay, checking and reduction; no JSON DOM.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TraceStore {
    #[doc = "header column or schema field."]
    pub header: Header,
    #[doc = "strings column or schema field."]
    pub strings: Interner,
    #[doc = "spine column or schema field."]
    pub spine: Spine,
    #[doc = "orders column or schema field."]
    pub orders: Orders,
    #[doc = "fills column or schema field."]
    pub fills: Fills,
    #[doc = "cash claims column or schema field."]
    pub cash_claims: CashClaims,
    #[doc = "position claims column or schema field."]
    pub position_claims: PositionClaims,
    #[doc = "units column or schema field."]
    pub units: Vec<Unit>,
    #[doc = "issues column or schema field."]
    pub issues: Vec<Issue>,
    #[doc = "delta cash column or schema field."]
    pub delta_cash: Vec<i128>,
    #[doc = "fill qty column or schema field."]
    pub fill_qty: Vec<i128>,
    #[doc = "cash scale column or schema field."]
    pub cash_scale: u8,
    #[doc = "starting cash column or schema field."]
    pub starting_cash: i128,
    #[doc = "prepared column or schema field."]
    pub prepared: bool,
}
impl TraceStore {
    /// Resolve an order symbol, including names first interned in another role.
    #[must_use]
    pub fn order_index(&self, name: &str) -> Option<usize> {
        let symbol = self.strings.lookup(name)?;
        self.orders.id.binary_search(&symbol).ok().or_else(|| {
            // Order/trade/claim strings share the arena. Reusing an earlier
            // symbol as a new order name can break numeric insertion order.
            self.orders.id.iter().position(|id| *id == symbol)
        })
    }
    /// Create empty typed columns. Validation belongs to the strict I/O builder.
    #[must_use]
    pub fn new(header: Header) -> Self {
        Self {
            header,
            strings: Interner::default(),
            spine: Spine::default(),
            orders: Orders::default(),
            fills: Fills::default(),
            cash_claims: CashClaims::default(),
            position_claims: PositionClaims::default(),
            units: Vec::new(),
            issues: Vec::new(),
            delta_cash: Vec::new(),
            fill_qty: Vec::new(),
            cash_scale: 0,
            starting_cash: 0,
            prepared: false,
        }
    }
    /// Number of events (not including the pinned header).
    #[must_use]
    pub fn len(&self) -> usize {
        self.spine.seq.len()
    }
    /// Whether there are no events.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }
    /// Account identity under the single-account model.
    #[must_use]
    pub fn account(&self) -> &str {
        self.header
            .accounts
            .first()
            .map_or("", |a| a.account_id.as_str())
    }
    /// Report malformed internal column shapes instead of indexing corrupt data.
    #[must_use]
    pub fn shape_valid(&self) -> bool {
        let n = self.len();
        let o = self.orders.id.len();
        let f = self.fills.order.len();
        [
            self.spine.ts.len(),
            self.spine.kind.len(),
            self.spine.unit.len(),
            self.spine.payload_idx.len(),
        ]
        .iter()
        .all(|v| *v == n)
            && [
                self.orders.instrument.len(),
                self.orders.side.len(),
                self.orders.qty_raw.len(),
                self.orders.qty_scale.len(),
                self.orders.unit.len(),
            ]
            .iter()
            .all(|v| *v == o)
            && [
                self.fills.trade.len(),
                self.fills.qty_raw.len(),
                self.fills.qty_scale.len(),
                self.fills.px_raw.len(),
                self.fills.px_scale.len(),
                self.fills.fee_raw.len(),
                self.fills.fee_scale.len(),
            ]
            .iter()
            .all(|v| *v == f)
            && self.cash_claims.raw.len() == self.cash_claims.scale.len()
            && self.cash_claims.raw.len() == self.cash_claims.text.len()
            && self.position_claims.raw.len() == self.position_claims.scale.len()
            && self.position_claims.raw.len() == self.position_claims.instrument.len()
            && self.position_claims.raw.len() == self.position_claims.text.len()
    }
    /// Compact completed columns; canonical claim text is reconstructed losslessly.
    pub fn compact(&mut self) {
        self.spine.seq.shrink_to_fit();
        self.spine.ts.shrink_to_fit();
        self.spine.kind.shrink_to_fit();
        self.spine.unit.shrink_to_fit();
        self.spine.payload_idx.shrink_to_fit();
        self.orders.id.shrink_to_fit();
        self.orders.instrument.shrink_to_fit();
        self.orders.side.shrink_to_fit();
        self.orders.qty_raw.shrink_to_fit();
        self.orders.qty_scale.shrink_to_fit();
        self.orders.unit.shrink_to_fit();
        self.fills.order.shrink_to_fit();
        self.fills.trade.shrink_to_fit();
        self.fills.qty_raw.shrink_to_fit();
        self.fills.qty_scale.shrink_to_fit();
        self.fills.px_raw.shrink_to_fit();
        self.fills.px_scale.shrink_to_fit();
        self.fills.fee_raw.shrink_to_fit();
        self.fills.fee_scale.shrink_to_fit();
        self.cash_claims.raw.shrink_to_fit();
        self.cash_claims.scale.shrink_to_fit();
        self.cash_claims.text.shrink_to_fit();
        self.position_claims.instrument.shrink_to_fit();
        self.position_claims.raw.shrink_to_fit();
        self.position_claims.scale.shrink_to_fit();
        self.position_claims.text.shrink_to_fit();
        self.units.shrink_to_fit();
        self.strings.compact();
    }
    /// Retained column capacities, excluding source JSONL bytes owned by I/O.
    #[must_use]
    pub fn column_bytes(&self) -> usize {
        self.spine.seq.capacity() * 8
            + self.spine.ts.capacity() * 8
            + self.spine.kind.capacity()
            + self.spine.unit.capacity() * 4
            + self.spine.payload_idx.capacity() * 4
            + self.delta_cash.capacity() * 16
            + self.fill_qty.capacity() * 16
            + self.orders.quantity_limit.capacity() * std::mem::size_of::<Option<i128>>()
            + self.orders.id.capacity() * 4
            + self.orders.instrument.capacity() * 4
            + self.orders.side.capacity()
            + self.orders.qty_raw.capacity() * 16
            + self.orders.qty_scale.capacity()
            + self.orders.unit.capacity() * 4
            + self.fills.order.capacity() * 4
            + self.fills.trade.capacity() * 4
            + self.fills.qty_raw.capacity() * 16
            + self.fills.qty_scale.capacity()
            + self.fills.px_raw.capacity() * 16
            + self.fills.px_scale.capacity()
            + self.fills.fee_raw.capacity() * 16
            + self.fills.fee_scale.capacity()
            + self.cash_claims.raw.capacity() * 16
            + self.cash_claims.scale.capacity()
            + self.cash_claims.text.capacity() * 4
            + self.position_claims.instrument.capacity() * 4
            + self.position_claims.raw.capacity() * 16
            + self.position_claims.scale.capacity()
            + self.position_claims.text.capacity() * 4
            + self.units.capacity() * std::mem::size_of::<Unit>()
            + self.strings.heap_bytes()
    }
}

/// Dense unit-alive bitset with deterministic set-bit iteration.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AliveMask {
    words: Vec<u64>,
    len: usize,
    first_seq: Option<u64>,
    last_seq: Option<u64>,
}
impl AliveMask {
    /// Restrict observed events to this inclusive sequence window.
    #[must_use]
    pub fn with_range(mut self, first: Option<u64>, last: Option<u64>) -> Self {
        self.first_seq = first;
        self.last_seq = last;
        self
    }
    /// Inclusive original-sequence bounds for clipped lifecycle segments.
    #[must_use]
    pub const fn bounds(&self) -> (Option<u64>, Option<u64>) {
        (self.first_seq, self.last_seq)
    }
    /// A unit may be alive while its removed prefix/suffix events are not.
    #[must_use]
    pub fn contains_event(&self, store: &TraceStore, event: usize) -> bool {
        store.spine.seq.get(event).is_some_and(|seq| {
            self.first_seq.is_none_or(|first| *seq >= first)
                && self.last_seq.is_none_or(|last| *seq <= last)
                && store
                    .spine
                    .unit
                    .get(event)
                    .is_some_and(|unit| self.contains(*unit as usize))
        })
    }
    /// Intersect unit bits; retain this mask's observation bounds.
    #[must_use]
    pub fn intersection(&self, other: &Self) -> Self {
        let mut result = self.clone();
        for (index, word) in result.words.iter_mut().enumerate() {
            *word &= other.words.get(index).copied().unwrap_or(0);
        }
        result
    }
    /// Number of live units, without constructing an index list.
    #[must_use]
    pub fn count(&self) -> usize {
        self.words
            .iter()
            .map(|word| word.count_ones() as usize)
            .sum()
    }
    /// Empty alive mask for this many units.
    #[must_use]
    pub fn empty(len: usize) -> Self {
        Self {
            words: vec![0; len.div_ceil(64)],
            len,
            first_seq: None,
            last_seq: None,
        }
    }
    /// Keep all units.
    #[must_use]
    pub fn all(len: usize) -> Self {
        let mut result = Self::empty(len);
        for id in 0..len {
            result.set(id, true);
        }
        result
    }
    /// Query a unit; out-of-range IDs are never alive.
    #[must_use]
    pub fn contains(&self, id: usize) -> bool {
        id < self.len
            && self
                .words
                .get(id / 64)
                .is_some_and(|word| word & (1_u64 << (id % 64)) != 0)
    }
    /// Set an in-range unit.
    pub fn set(&mut self, id: usize, alive: bool) {
        if id < self.len
            && let Some(word) = self.words.get_mut(id / 64)
        {
            if alive {
                *word |= 1_u64 << (id % 64);
            } else {
                *word &= !(1_u64 << (id % 64));
            }
        }
    }
    /// Sorted live unit indices, using trailing-zero scans.
    pub fn iter(&self) -> impl Iterator<Item = usize> + '_ {
        self.words
            .iter()
            .enumerate()
            .flat_map(|(word_index, &word)| {
                let mut remaining = word;
                std::iter::from_fn(move || {
                    if remaining == 0 {
                        return None;
                    }
                    let bit = remaining.trailing_zeros() as usize;
                    remaining &= remaining.wrapping_sub(1);
                    Some(word_index * 64 + bit)
                })
            })
            .filter(|id| *id < self.len)
    }
    /// Canonical words for predicate content hashing.
    #[must_use]
    pub fn words(&self) -> &[u64] {
        &self.words
    }
    /// Number of allocated unit slots.
    #[must_use]
    pub fn len(&self) -> usize {
        self.len
    }
    /// Whether the mask has no slots.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.len == 0
    }
}

/// Explicitly labelled expected-state replacement for a removed prefix.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SyntheticCheckpoint {
    /// Version 1 preserves orders/trades; absent in legacy checkpoints.
    #[serde(default, skip_serializing_if = "legacy_checkpoint_version")]
    pub schema_version: u16,
    #[doc = "provenance column or schema field."]
    pub provenance: String,
    #[doc = "account id column or schema field."]
    pub account_id: String,
    #[doc = "currency column or schema field."]
    pub currency: String,
    #[doc = "cash column or schema field."]
    pub cash: String,
    #[doc = "positions column or schema field."]
    pub positions: Vec<CheckpointPosition>,
    #[doc = "cut seq column or schema field."]
    pub cut_seq: u64,
    #[doc = "source digest column or schema field."]
    pub source_digest: String,
    #[doc = "description column or schema field."]
    pub description: String,
    /// Referenced lifecycle states, including terminal states needed by I3.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub orders: Vec<CheckpointOrder>,
    /// Previously seen trade IDs relevant to retained fills.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub trades: Vec<CheckpointTrade>,
    /// Observed opening cash claim plus independent movement since that claim.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub cash_window: Option<CheckpointCashWindow>,
    /// Per-instrument observed opening claims and independent pending movement.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub position_windows: Vec<CheckpointPositionWindow>,
}

/// Lifecycle state replacing removed order history; all amounts are exact.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CheckpointOrder {
    /// Original order identity.
    pub client_order_id: String,
    /// Instrument declared in the original order.
    pub instrument_id: String,
    /// Original side.
    pub side: Side,
    /// Original submitted quantity.
    pub quantity: String,
    /// State immediately before the checkpoint boundary.
    pub status: OrderState,
    /// Filled quantity immediately before the boundary.
    pub filled_quantity: String,
}
/// A prior trade identity required to check cross-boundary uniqueness.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CheckpointTrade {
    /// Instrument scope of uniqueness.
    pub instrument_id: String,
    /// Original trade identity.
    pub trade_id: String,
}
/// Opening cash evidence is a boundary, not a fresh assertion to audit.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CheckpointCashWindow {
    /// Original opening claim sequence, or the header balance.
    pub seq: Option<u64>,
    /// Unmodified observed value (header starting balance when seq is absent).
    pub observed: String,
    /// Independently computed movement after the claim and before the cut.
    pub delta: String,
}
/// Per-instrument opening position evidence for a local I2 window.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CheckpointPositionWindow {
    /// Instrument identity.
    pub instrument_id: String,
    /// Original opening claim sequence, or zero starting position.
    pub seq: Option<u64>,
    /// Unmodified observed quantity.
    pub observed: String,
    /// Independent signed quantity movement since the opening claim.
    pub delta: String,
}
/// One checkpoint position, encoded as an exact decimal string.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CheckpointPosition {
    #[doc = "instrument id column or schema field."]
    pub instrument_id: String,
    #[doc = "net qty column or schema field."]
    pub net_qty: String,
}

#[allow(clippy::trivially_copy_pass_by_ref)]
fn legacy_checkpoint_version(version: &u16) -> bool {
    *version == 0
}
