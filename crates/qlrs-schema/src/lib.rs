pub enum CashRounding {
    #[default]
    #[doc = "Exact state or tag."]
    Exact,
    #[doc = "`HalfEven` state or tag."]
    HalfEven,
    #[doc = "`HalfUp` state or tag."]
    HalfUp,
    #[doc = "Down state or tag."]
    Down,
}
impl CashRounding {
    /// Corresponding numeric rounding mode.
    #[must_use]
    pub const fn numeric(self) -> qlrs_num::Rounding {
        match self {
            Self::Exact => qlrs_num::Rounding::Exact,
            Self::HalfEven => qlrs_num::Rounding::HalfEven,
            Self::HalfUp => qlrs_num::Rounding::HalfUp,
            Self::Down => qlrs_num::Rounding::Down,
        }
    }
}

